"""Build hover-preview cards for the links in README.md and write them to link_previews.js.

- arXiv papers: title, authors, and abstract (from the arXiv API)
- LessWrong posts: title and opening of the post (from the LessWrong API)
- other web pages: the page's own og:description / meta description, if it has one
Local files (CV, slides) get no preview. Run `python3 compile.py` afterwards.
"""
import html
import json
import re
import urllib.error
import urllib.request
import xml.etree.ElementTree as ET

ATOM = "{http://www.w3.org/2005/Atom}"
ARXIV_RE = re.compile(r"arxiv\.org/abs/(\d{4}\.\d{4,5})")
LW_RE = re.compile(r"lesswrong\.com/posts/([A-Za-z0-9]+)")
MAX_EXCERPT_CHARS = 600
HEADERS = {"User-Agent": "Mozilla/5.0"}


def fetch(url, data=None, headers=None):
    req = urllib.request.Request(url, data=data, headers={**HEADERS, **(headers or {})})
    with urllib.request.urlopen(req) as resp:
        return resp.read().decode("utf-8", errors="replace")


def squash(s):
    return " ".join(s.split())


def truncate(s, n=MAX_EXCERPT_CHARS):
    if len(s) <= n:
        return s
    return s[:n].rsplit(" ", 1)[0] + "…"


def clean_latex_text(s):
    """Strip text-mode LaTeX macros that KaTeX (which only renders $...$ math) can't handle."""
    s = re.sub(r"\\(?:defn|emph|textit|textbf)\{([^}]*)\}", r"\1", s)
    return re.sub(r"\\cite\{([^}]*)\}", r"[\1]", s)


def arxiv_previews(urls):
    ids = {ARXIV_RE.search(u)[1]: u for u in urls}
    feed = ET.fromstring(fetch(
        f"https://export.arxiv.org/api/query?id_list={','.join(ids)}&max_results={len(ids)}"
    ))
    previews = {}
    for entry in feed.findall(f"{ATOM}entry"):
        arxiv_id = ARXIV_RE.search(entry.find(f"{ATOM}id").text)[1]
        previews[ids[arxiv_id]] = {
            "title": squash(entry.find(f"{ATOM}title").text),
            "authors": ", ".join(a.find(f"{ATOM}name").text for a in entry.findall(f"{ATOM}author")),
            "text": clean_latex_text(squash(entry.find(f"{ATOM}summary").text)),
            "math": True,
        }
    missing = set(ids.values()) - set(previews)
    assert not missing, f"arXiv returned no entry for {missing}"
    return previews


def lesswrong_previews(urls):
    urls = list(urls)
    fields = " ".join(
        f'p{i}: post(input:{{selector:{{_id:"{LW_RE.search(u)[1]}"}}}}){{ result {{ title contents {{ plaintextDescription }} }} }}'
        for i, u in enumerate(urls)
    )
    data = json.loads(fetch(
        "https://www.lesswrong.com/graphql",
        data=json.dumps({"query": f"{{ {fields} }}"}).encode(),
        headers={"Content-Type": "application/json"},
    ))["data"]
    previews = {}
    for i, u in enumerate(urls):
        post = data[f"p{i}"]["result"]
        text = re.sub(r"\[\d+\]", "", post["contents"]["plaintextDescription"])  # footnote markers
        previews[u] = {"title": squash(post["title"]), "text": truncate(squash(text))}
    return previews


def meta_description(page_html):
    for attr in ("property", "name"):
        for key in ("og:description", "description"):
            m = re.search(
                rf'<meta[^>]*{attr}=(["\']){key}\1[^>]*content=(["\'])(?P<c>.*?)\2', page_html, re.I
            ) or re.search(
                rf'<meta[^>]*content=(["\'])(?P<c>.*?)\1[^>]*{attr}=(["\']){key}\3', page_html, re.I
            )
            if m and m["c"].strip():
                return squash(html.unescape(m["c"]))
    return None


def page_title(page_html):
    m = re.search(r"<title[^>]*>(.*?)</title>", page_html, re.I | re.S)
    return squash(html.unescape(m[1])) if m else None


def other_previews(urls):
    previews = {}
    for u in urls:
        try:
            page = fetch(u)
        except urllib.error.HTTPError as e:  # a dead link shouldn't stop the whole build
            print(f"  no preview for {u} (HTTP {e.code})")
            continue
        description = meta_description(page)
        if description is None:
            print(f"  no preview for {u} (page has no description)")
            continue
        previews[u] = {"title": page_title(page) or u, "text": truncate(description)}
    return previews


with open("README.md", encoding="utf-8") as f:
    readme = f.read()
links = set(re.findall(r'\]\((https?://[^)\s]+)\)', readme)) | set(re.findall(r'href="(https?://[^"]+)"', readme))

arxiv = {u for u in links if ARXIV_RE.search(u)}
lesswrong = {u for u in links if LW_RE.search(u)}
other = sorted(links - arxiv - lesswrong)

previews = {**arxiv_previews(arxiv), **lesswrong_previews(lesswrong), **other_previews(other)}

with open("link_previews.js", "w", encoding="utf-8") as f:
    f.write("// Generated by update_link_previews.py; do not edit by hand.\n")
    f.write("// Keys are hrefs exactly as written in README.md.\n")
    f.write(f"const LINK_PREVIEWS = {json.dumps(previews, indent=2, ensure_ascii=False)};\n")

print(f"Wrote {len(previews)} link previews to link_previews.js "
      f"({len(arxiv)} arXiv, {len(lesswrong)} LessWrong, {len(previews) - len(arxiv) - len(lesswrong)} other)")
